def write_html_dashboard(
    all_platform_results: dict[str, list[AgentResult]],
    output_dir: Path,
) -> Path:
    """Generate a single-file HTML comparison dashboard."""
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / "comparison.html"

    platform_names = list(all_platform_results.keys())

    # Cards
    cards_html_parts = []
    for name in platform_names:
        ar_list = all_platform_results[name]
        total = sum(dr.total_points for ar in ar_list for dr in ar.domain_results)
        potemkin = sum(len(ar.potemkin_flags) for ar in ar_list)
        pending = sum(len(ar.pending_questions) for ar in ar_list)
        dq_fails = sum(
            1 for ar in ar_list for dq in ar.disqualifier_results
            if dq.get("status") == "FAIL"
        )
        cards_html_parts.append(f"""
<div class="card">
<h3>{_escape(name)}</h3>
<div class="score-big">{total:.1f}<span class="score-max"> / 100</span></div>
<div class="meta">
<span class="badge dq" title="Disqualifier failures">DQ: {dq_fails}</span>
<span class="badge p" title="Potemkin claims flagged">Potemkin: {potemkin}</span>
<span class="badge pen" title="Tests marked PENDING">Pending: {pending}</span>
</div>
</div>
""")

    # Platform headers (for tables)
    platform_headers = "".join(f"<th>{_escape(p)}</th>" for p in platform_names)

    # Domain rows
    domain_rows_parts = []
    for d_code in sorted(DOMAINS.keys(), key=lambda c: int(c[1:])):
        domain = DOMAINS[d_code]
        row = [f"<td><strong>{d_code}</strong> {_escape(domain.name)}</td>", f"<td>{domain.points}</td>"]
        for p in platform_names:
            ar_list = all_platform_results[p]
            d_score = None
            for ar in ar_list:
                for dr in ar.domain_results:
                    if dr.domain_code == d_code:
                        d_score = dr.total_points
            if d_score is None:
                row.append("<td>—</td>")
            else:
                pct = (d_score / domain.points * 100) if domain.points > 0 else 0
                color = "pass" if pct >= 75 else "partial" if pct >= 40 else "fail" if d_score > 0 else ""
                row.append(
                    f'<td><div class="bar-container">'
                    f'<div class="bar {color}" style="width: {pct}%;"></div>'
                    f'<div class="bar-label">{d_score:.1f}</div>'
                    f'</div></td>'
                )
        domain_rows_parts.append("<tr>" + "".join(row) + "</tr>")

    # Pre-filter & disqualifier rows
    pf_dq_rows_parts = []
    all_pf_ids = set()
    all_dq_ids = set()
    for ar_list in all_platform_results.values():
        for ar in ar_list:
            for pf in ar.pre_filter_results:
                all_pf_ids.add(pf.get("id"))
            for dq in ar.disqualifier_results:
                all_dq_ids.add(dq.get("id"))

    for qa_id in sorted(all_pf_ids):
        row = [f"<td><strong>{qa_id}</strong></td>"]
        for p in platform_names:
            status = "—"
            for ar in all_platform_results[p]:
                for pf in ar.pre_filter_results:
                    if pf.get("id") == qa_id:
                        status = pf.get("status", "—")
            row.append(f"<td>{_escape(status)}</td>")
        pf_dq_rows_parts.append("<tr>" + "".join(row) + "</tr>")

    for dq_id in sorted(all_dq_ids):
        row = [f"<td><strong>{dq_id}</strong></td>"]
        for p in platform_names:
            status = "—"
            for ar in all_platform_results[p]:
                for dq in ar.disqualifier_results:
                    if dq.get("id") == dq_id:
                        status = dq.get("status", "—")
            row.append(f"<td>{_escape(status)}</td>")
        pf_dq_rows_parts.append("<tr>" + "".join(row) + "</tr>")

    # Potemkin
    all_potemkin = []
    for p in platform_names:
        for ar in all_platform_results[p]:
            for flag in ar.potemkin_flags:
                all_potemkin.append({**flag, "platform": p})

    potemkin_html = ""
    if all_potemkin:
        for f in all_potemkin:
            potemkin_html += f"""
<div class="potemkin-item">
<span class="pattern-id">[{_escape(f.get('pattern_id', '?'))}] {_escape(f.get('pattern_name', ''))}</span>
&nbsp;<strong>Platform:</strong> {_escape(f.get('platform', ''))}<br>
<strong>Claim:</strong> {_escape(f.get('vendor_claim', ''))}<br>
<strong>Actual evidence supports:</strong> {_escape(f.get('actual_evidence_level', ''))}<br>
<strong>Why:</strong> {_escape(f.get('explanation', ''))}
</div>
"""
    else:
        potemkin_html = "<p><em>No Potemkin claims flagged.</em></p>"

    # JSON for embedded data
    data_for_json = {
        "platforms": platform_names,
        "scores": {
            p: {
                "total": sum(dr.total_points for ar in all_platform_results[p] for dr in ar.domain_results),
                "by_domain": {
                    dr.domain_code: dr.total_points
                    for ar in all_platform_results[p]
                    for dr in ar.domain_results
                },
            }
            for p in platform_names
        },
    }

    html = HTML_TEMPLATE.format(
        n_platforms=len(platform_names),
        cards_html="\n".join(cards_html_parts),
        platform_headers=platform_headers,
        domain_rows="\n".join(domain_rows_parts),
        pf_dq_rows="\n".join(pf_dq_rows_parts),
        total_potemkin=len(all_potemkin),
        potemkin_html=potemkin_html,
        data_json=json.dumps(data_for_json),
    )

    output_path.write_text(html, encoding="utf-8")
    logger.info("Wrote HTML dashboard: %s", output_path)
    return output_path


def _escape(s) -> str:
    """Minimal HTML escape."""
    if s is None:
        return ""
    return (
        str(s)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )
